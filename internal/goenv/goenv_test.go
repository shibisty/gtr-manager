func TestHints(t *testing.T) {
	for line, want := range map[string]string{
		`main.go:3:8: package orm is not in std (/usr/local/go/src/orm)`:                                                      `package "orm" is not installed`,
		`go: malformed module path "orm": missing dot in first path element`:                                                  `package "orm" is not installed`,
		`main.go:4:2: no required module provides package github.com/google/uuid/v5/x; to add it:`:                            "gtr add github.com/google/uuid/v5`",
		`main.go:4:2: cannot find module providing package golang.org/x/sync/errgroup: module lookup disabled by GOPROXY=off`: "gtr add golang.org/x/sync`",
		`go: github.com/a/b@v1.0.0: module lookup disabled by GOPROXY=off`:                                                    "installed by gtr, not downloaded",
		`main.go:3:8: ambiguous import: found package errors in multiple modules:`:                                            `"errors" is provided twice`,
		`go: updates to go.mod needed; to update it:`:                                                                         "gtr install",
		`main.go:1:1: undefined: x`: "",
	} {
		if got := Hint(line); want == "" && got != "" || !strings.Contains(got, want) {
			t.Errorf("%q → %q, want %q", line, got, want)
		}
	}
	var out bytes.Buffer
	h := NewHints(&out)
	h.Write([]byte("a.go:1:1: package orm is not in std (/go/src/orm)\nb.go:1:1: package orm is not in std (/go/src/orm)\npartial"))
	h.Write([]byte(" line\nno newline"))
	h.Close()
	lines := strings.Split(strings.TrimSuffix(out.String(), "\n"), "\n")
	if len(lines) != 5 || !strings.HasPrefix(lines[1], "gtr: ") || lines[3] != "partial line" || lines[4] != "no newline" {
		t.Fatalf("%q", lines)
	}
}

func TestGenerated(t *testing.T) {
	dir := t.TempDir()
	if Generated(dir) {
		t.Fatal("no go.mod")
	}
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module x\n"), 0o644)
	if Generated(dir) {
		t.Fatal("foreign go.mod")
	}
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("// generated by gtr from gtr.json — edit gtr.json or run `gtr sync`\r\nmodule x\n"), 0o644)
	if !Generated(dir) {
		t.Fatal("generated go.mod")
	}
}

func TestEnv(t *testing.T) {
	get := func(env []string, k string) (string, int) {
		v, n := "", 0
		for _, kv := range env {
			if strings.HasPrefix(kv, k+"=") {
				v, n = strings.TrimPrefix(kv, k+"="), n+1
			}
		}
		return v, n
	}
	file := filepath.Join(t.TempDir(), "env")
	os.WriteFile(file, []byte("GOFLAGS=-tags=fromfile\nGOPROXY=direct\n"), 0o644)
	if v, _ := get(Env([]string{"GOENV=" + file}, ""), "GOFLAGS"); v != "-tags=fromfile -mod=mod" {
		t.Errorf("GOFLAGS from the go env file: %q", v)
	}
	if v, _ := get(Env([]string{"GOENV=" + file, "GOFLAGS="}, ""), "GOFLAGS"); v != "-mod=mod" {
		t.Errorf("an empty GOFLAGS variable hides the file: %q", v)
	}
	env := Env([]string{"PATH=/bin", "GOPROXY=https://proxy.golang.org", "GOFLAGS=-tags=x", "GOWORK=/w/go.work"}, "")
	for k, want := range map[string]string{"GOPROXY": "off", "GOWORK": "off", "GOFLAGS": "-tags=x -mod=mod", "PATH": "/bin"} {
		if v, n := get(env, k); v != want || n != 1 {
			t.Errorf("%s = %q (%d times), want %q", k, v, n, want)
		}
	}
	if v, _ := get(Env([]string{"GOFLAGS=-mod=vendor"}, ""), "GOFLAGS"); v != "-mod=vendor" {
		t.Errorf("an explicit -mod is kept: %q", v)
	}
	if v, _ := get(Env([]string{"GOENV=off"}, ""), "GOFLAGS"); v != "-mod=mod" {
		t.Errorf("GOFLAGS = %q", v)
	}
}

func TestWorkspace(t *testing.T) {
	root := t.TempDir()
	member := filepath.Join(root, "drivers", "pg")
	os.MkdirAll(member, 0o755)
	if FindWork(member) != "" {
		t.Fatal("no go.work")
	}
	os.WriteFile(filepath.Join(root, "go.work"), []byte("go 1.22\n"), 0o644)
	if FindWork(member) != "" {
		t.Fatal("a go.work gtr did not write")
	}
	work := filepath.Join(root, "go.work")
	os.WriteFile(work, []byte("// generated by gtr from gtr.json — edit gtr.json or run `gtr sync`\ngo 1.23.1\n\nuse (\n\t.\n\t./drivers/pg\n\t\"./my lib\"\n)\n"), 0o644)
	if FindWork(member) != "" {
		t.Fatal("a directory without a go.mod is not a workspace module")
	}
	os.WriteFile(filepath.Join(member, "go.mod"), []byte("module orm-pg\n"), 0o644)
	if FindWork(member) != work || FindWork(filepath.Join(member, "sub")) != work || WorkGo(work) != "1.23.1" {
		t.Fatalf("FindWork = %q", FindWork(member))
	}
	quoted := filepath.Join(root, "my lib")
	os.MkdirAll(quoted, 0o755)
	os.WriteFile(filepath.Join(quoted, "go.mod"), []byte("module mylib\n"), 0o644)
	if FindWork(quoted) != work {
		t.Fatal("quoted use path")
	}
	// A project nested in the workspace without being a member builds alone.
	other := filepath.Join(root, "drivers", "skip")
	os.MkdirAll(other, 0o755)
	os.WriteFile(filepath.Join(other, "go.mod"), []byte("module skip\n"), 0o644)
	if FindWork(other) != "" {
		t.Fatal("not a member")
	}
	env := strings.Join(Env([]string{"GOFLAGS=-mod=mod -tags=x", "GOWORK=off"}, work), "\n")
	if !strings.Contains(env, "GOWORK="+work+"\n") || !strings.Contains(env, "GOFLAGS=-tags=x") || strings.Contains(env, "-mod=mod") || !strings.Contains(env, "GOPROXY=off") {
		t.Fatalf("workspace env:\n%s", env)
	}
}


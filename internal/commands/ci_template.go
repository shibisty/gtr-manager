package commands

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"gtr-manager/internal/manifest"
)

// CIWorkflow is where gtr init --ci writes the GitHub Actions workflow.
const CIWorkflow = ".github/workflows/ci.yml"

var minGoRe = regexp.MustCompile(`^\s*>=?\s*v?(\d+\.\d+(\.\d+)?)\s*$`)

// ciGoVersions are the Go versions the workflow tests with: the minimum
// engines.go allows and the newest it allows (GTR_GO_VERSION takes both).
func ciGoVersions(engine string) []string {
	if m := minGoRe.FindStringSubmatch(engine); m != nil {
		return []string{m[1], ">=" + m[1]}
	}
	if engine != "" {
		return []string{engine}
	}
	return []string{"*"}
}

// ciWorkflow is the GitHub Actions workflow of a gtr project: install gtr,
// then `gtr ci` and `gtr test --coverage` on Linux, Windows and macOS.
func ciWorkflow(m *manifest.Manifest) string {
	var goList []string
	for _, v := range ciGoVersions(m.Engines.Go) {
		goList = append(goList, fmt.Sprintf("%q", v))
	}
	return `# generated by gtr init --ci; edit freely
name: CI

on:
  push:
    branches: [main, master]
    tags: ["*"]
  pull_request:

permissions:
  contents: read

jobs:
  test:
    name: go ${{ matrix.go }} (${{ matrix.os }})
    runs-on: ${{ matrix.os }}
    strategy:
      fail-fast: false
      matrix:
        os: [ubuntu-latest, windows-latest, macos-latest]
        go: [` + strings.Join(goList, ", ") + `]
    env:
      GTR_GO_VERSION: ${{ matrix.go }} # gtr downloads this Go (engines.go in gtr.json)
      GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }} # higher GitHub API limits for gtr ci
    steps:
      - uses: actions/checkout@v4
      - name: install gtr
        if: runner.os != 'Windows'
        shell: bash
        run: |
          curl -fsSL https://raw.githubusercontent.com/shibisty/gtr/main/install.sh | GTR_NO_MODIFY_PATH=1 sh
          echo "$HOME/.gtr/bin" >> "$GITHUB_PATH"
      - name: install gtr (Windows)
        if: runner.os == 'Windows'
        shell: pwsh
        run: |
          $env:GTR_NO_MODIFY_PATH = '1'
          irm https://raw.githubusercontent.com/shibisty/gtr/main/install.ps1 | iex
          "$HOME\.gtr\bin" | Out-File -Append -Encoding utf8 $env:GITHUB_PATH
      - name: install dependencies (gtr.lock)
        run: gtr ci
      - name: vet
        run: go vet ./... # the go shim of gtr: the Go of engines.go, with gtr_modules
      - name: test
        run: gtr test --coverage
`
}

// writeCI writes the workflow unless one exists.
func writeCI(dir string, m *manifest.Manifest) error {
	path := filepath.Join(dir, filepath.FromSlash(CIWorkflow))
	if _, err := os.Stat(path); err == nil {
		return fmt.Errorf("%s already exists; delete it to generate it again", CIWorkflow)
	} else if !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(ciWorkflow(m)), 0o644); err != nil {
		return err
	}
	fmt.Fprintf(Stdout, "Created %s (gtr ci && gtr test --coverage on Linux, Windows and macOS)\n", CIWorkflow)
	return nil
}
